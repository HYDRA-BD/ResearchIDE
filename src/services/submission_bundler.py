"""Submission Package Bundler for ResearchIDE.

Packages clean compiled PDFs, LaTeX sources, BibTeX databases, figures,
and compliance checklists into submission-ready ZIP archives.
"""
from __future__ import annotations
import zipfile
import shutil
from pathlib import Path
from typing import List, Optional
from src.services.compliance_auditor import ComplianceReport
from src.utils.logger import app_logger


class SubmissionBundler:
    """Assembles reproducible academic submission packages."""

    @classmethod
    def create_submission_package(
        cls,
        project_dir: Path,
        main_tex_file: Path,
        compiled_pdf_file: Optional[Path],
        output_zip_path: Path,
        compliance_report: Optional[ComplianceReport] = None,
    ) -> Path:
        """Bundle source files, bibliography, figures, PDF, and checklist into a ZIP."""
        project_dir = Path(project_dir).resolve()
        output_zip_path = Path(output_zip_path).resolve()
        output_zip_path.parent.mkdir(parents=True, exist_ok=True)

        with zipfile.ZipFile(output_zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            # 1. Add main .tex source
            if main_tex_file.exists():
                zf.write(main_tex_file, arcname=main_tex_file.name)

            # 2. Add compiled PDF if present
            if compiled_pdf_file and compiled_pdf_file.exists():
                zf.write(compiled_pdf_file, arcname=compiled_pdf_file.name)

            # 3. Add all .bib files from project root or src/
            for bib_file in project_dir.glob("**/*.bib"):
                if ".researchide" not in str(bib_file):
                    rel = bib_file.relative_to(project_dir)
                    zf.write(bib_file, arcname=str(rel))

            # 4. Add all figures and images from assets/ or figures/
            for asset_ext in ("*.png", "*.jpg", "*.jpeg", "*.pdf", "*.eps", "*.svg"):
                for asset in project_dir.glob(f"assets/**/{asset_ext}"):
                    rel = asset.relative_to(project_dir)
                    zf.write(asset, arcname=str(rel))

            # 5. Generate and add SUBMISSION_CHECKLIST.md
            checklist_md = cls._generate_checklist_md(compliance_report, main_tex_file.name)
            zf.writestr("SUBMISSION_CHECKLIST.md", checklist_md)

        app_logger.info(f"Submission bundle packaged successfully: '{output_zip_path}'")
        return output_zip_path

    @classmethod
    def _generate_checklist_md(cls, report: Optional[ComplianceReport], tex_name: str) -> str:
        """Produce markdown submission checklist report."""
        lines = [
            "# ACADEMIC SUBMISSION CHECKLIST",
            f"**Manuscript:** {tex_name}  ",
            f"**Target Publication:** {report.template_name if report else 'General Academic'}  ",
            "**Generated By:** ResearchIDE Offline Academic Environment  ",
            "",
            "---",
            "",
            "## 1. Compliance Audit Results",
        ]

        if report:
            lines.append("### Passed Checks")
            for c in report.passed_checks:
                lines.append(f"- [x] {c}")

            if report.failed_checks:
                lines.append("\n### Failed / Action Required")
                for f in report.failed_checks:
                    lines.append(f"- [ ] ❌ **{f}**")

            if report.warnings:
                lines.append("\n### Warnings")
                for w in report.warnings:
                    lines.append(f"- [ ] ⚠️ {w}")

            lines.append("\n### Mandatory Manual Verification Steps")
            for m in report.manual_verifications:
                lines.append(f"- [ ] {m}")
        else:
            lines.append("No automated compliance report attached.")

        lines.extend([
            "",
            "---",
            "### Disclaimer",
            "Automated compliance checks are diagnostic guides only and do not guarantee editorial acceptance.",
        ])

        return "\n".join(lines)
